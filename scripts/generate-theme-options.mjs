// Regenerates lib/theme.ts's THEMES array from app/themes.css (the source
// of truth for all 187 official Monkeytype theme colors). Run with:
//   npm run generate:themes
import { readFileSync, writeFileSync } from "fs";
import { fileURLToPath } from "url";
import path from "path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const cssPath = path.join(root, "app", "themes.css");
const outPath = path.join(root, "lib", "theme.ts");

const css = readFileSync(cssPath, "utf8");
const blockRe = /:root\[data-theme="([^"]+)"\]\s*\{([^}]*)\}/g;
const varRe = /--([\w-]+):\s*([^;]+);/g;

const entries = [];
let match;
while ((match = blockRe.exec(css)) !== null) {
  const [, id, body] = match;
  const vars = {};
  let varMatch;
  while ((varMatch = varRe.exec(body)) !== null) {
    vars[varMatch[1]] = varMatch[2].trim();
  }

  for (const required of ["background", "foreground", "sub", "accent"]) {
    if (!vars[required]) {
      throw new Error(`Theme "${id}" is missing --${required} in app/themes.css`);
    }
  }

  entries.push({
    id,
    label: id.replace(/_/g, " "),
    background: vars.background,
    foreground: vars.foreground,
    sub: vars.sub,
    accent: vars.accent,
  });
}

if (entries.length !== 187) {
  throw new Error(`Expected 187 themes, parsed ${entries.length} — app/themes.css may have changed shape`);
}

const entryLines = entries
  .map(
    (t) =>
      `  { id: "${t.id}", label: "${t.label}", background: "${t.background}", foreground: "${t.foreground}", sub: "${t.sub}", accent: "${t.accent}" },`
  )
  .join("\n");

const content = `export interface ThemeOption {
  id: string;
  label: string;
  background: string;
  foreground: string;
  sub: string;
  accent: string;
}

// Keep in sync with the inline bootstrap script in app/layout.tsx, which
// can't import this constant since it must run before any JS module loads.
export const THEME_STORAGE_KEY = "quizai-theme";

export const DEFAULT_THEME_ID = "serika_dark";

// All 187 official Monkeytype themes (frontend/src/ts/constants/themes.ts in
// monkeytypegame/monkeytype), mapped onto this app's CSS variables in
// app/globals.css. Generated by scripts/generate-theme-options.mjs from
// app/themes.css — do not hand-edit entries, run \`npm run generate:themes\`
// instead.
export const THEMES: ThemeOption[] = [
${entryLines}
];

export function isThemeId(value: string): boolean {
  return THEMES.some((t) => t.id === value);
}
`;

writeFileSync(outPath, content);
console.log(`Wrote ${entries.length} themes to lib/theme.ts`);
